"""Database models for Assistant Conversations, Messages, and Fix Proposals."""

import uuid

from sqlalchemy import ForeignKey, Integer, String, Text
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.db.base import TenantBaseModel


class Conversation(TenantBaseModel):
    """Conversation thread scoped to a specific architectural plan and organization."""

    __tablename__ = "conversations"

    plan_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("plans.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    title: Mapped[str] = mapped_column(String(255), default="Plan Review Discussion", nullable=False)

    messages: Mapped[list["Message"]] = relationship(
        "Message",
        back_populates="conversation",
        cascade="all, delete-orphan",
        order_by="Message.created_at",
    )


class Message(TenantBaseModel):
    """Single chat message or tool interaction within an assistant conversation."""

    __tablename__ = "messages"

    conversation_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("conversations.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    role: Mapped[str] = mapped_column(String(32), nullable=False)  # user, assistant, system, tool
    content: Mapped[str | None] = mapped_column(Text, nullable=True)
    tool_calls: Mapped[list[dict] | None] = mapped_column(JSONB, nullable=True)
    tool_call_id: Mapped[str | None] = mapped_column(String(128), nullable=True)

    conversation: Mapped["Conversation"] = relationship("Conversation", back_populates="messages")


class Fix(TenantBaseModel):
    """Statutory fix proposal generated by the assistant.
    propose_fix NEVER applies automatically; only user action on apply endpoint creates a new plan version.
    """

    __tablename__ = "fixes"

    plan_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("plans.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    conversation_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("conversations.id", ondelete="SET NULL"),
        nullable=True,
        index=True,
    )
    status: Mapped[str] = mapped_column(
        String(32), default="proposed", nullable=False, index=True
    )  # proposed, applied, skipped
    rationale: Mapped[str] = mapped_column(Text, nullable=False)
    rule_id: Mapped[str] = mapped_column(String(128), nullable=False)
    clause: Mapped[str | None] = mapped_column(String(255), nullable=True)
    patch_ops: Mapped[list[dict]] = mapped_column(JSONB, nullable=False)
    diff_summary: Mapped[dict] = mapped_column(JSONB, nullable=False)
    introduced_fails: Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    applied_version: Mapped[int | None] = mapped_column(Integer, nullable=True)
